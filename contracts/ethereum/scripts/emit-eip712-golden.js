/**
 * Emit the EIP-712 golden vector the Rust backend checks itself against.
 *
 *     cd contracts/ethereum && npx hardhat run scripts/emit-eip712-golden.js
 *
 * ## Why this exists
 *
 * The backend has to reproduce three things the contract computes: the order
 * hash, the domain separator and the quote digest. All three are built on
 * Solidity's ABI encoding, which has rules that are easy to get almost right --
 * static values left-padded into 32-byte slots, dynamic members replaced by a
 * head offset and a right-padded tail, and dynamic members *inside* a struct
 * hash replaced by their own hash instead. Three rules, used in three places.
 *
 * A mistake cannot let anything through: the contract recovers the signer from
 * the digest it computes, so a wrong digest recovers the wrong address and the
 * order is refused. What it costs is every payment failing with
 * `InvalidQuoteSignature`, an error that points at the key rather than at the
 * message. This vector turns that into a failing unit test instead.
 *
 * The values come from the contract's own view functions, deployed to an
 * in-memory chain -- not from a second implementation in JavaScript, which
 * would only prove the two JavaScript versions agree.
 */
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

// Fixed, so the vector is stable in a diff. The addresses are Hardhat's own
// deterministic accounts; the amount is deliberately above 2^64 so the file
// also pins that wide values survive.
const INPUT = {
  orderId: "3f8a1c2e-0b4d-4e6f-9a1b-2c3d4e5f6071",
  buyer: "0x70997970C51812dc3A010C7d01b50e0d17dc79C8",
  seller: "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC",
  // The all-zero address is the contract's sentinel for the native coin.
  token: "0x0000000000000000000000000000000000000000",
  // 20 ether in wei: 2e19, which does not fit in a uint64.
  amount: "20000000000000000000",
  fee: "2608695652173913043",
  expiry: "1900000000",
  chainId: 31337,
};

/**
 * A well-known Ethereum test key. It controls nothing on any chain, and it is
 * fixed here so the signature in the vector is reproducible -- the Rust backend
 * asserts it produces these exact bytes from the same key and payload.
 *
 * Matching ethers byte for byte is the point. The Hardhat suite already proves
 * the contract accepts ethers-produced signatures, so a Rust signature that is
 * identical to one is a signature the contract accepts, without having to get a
 * Rust-produced signature into a Solidity test.
 */
const QUOTE_SIGNER_KEY =
  "0x4c0883a69102937d6231471b5dbb6204fe5129617082792ae468d01a3f362318";

async function main() {
  const [deployer, , , treasury] = await hre.ethers.getSigners();
  const quoteSigner = new hre.ethers.Wallet(QUOTE_SIGNER_KEY);

  const Escrow = await hre.ethers.getContractFactory("AeroLedgerEscrow");
  const escrow = await Escrow.deploy(
    deployer.address,
    quoteSigner.address,
    treasury.address,
    3600, // refundWindow: the minimum the contract allows
  );
  await escrow.waitForDeployment();
  const verifyingContract = await escrow.getAddress();

  const orderHash = await escrow.computeOrderHash(INPUT.buyer, INPUT.orderId);
  const domainSeparator = await escrow.domainSeparator();
  const quoteDigest = await escrow.quoteDigest(
    orderHash,
    INPUT.buyer,
    INPUT.seller,
    INPUT.token,
    INPUT.amount,
    INPUT.fee,
    INPUT.expiry,
  );

  const network = await hre.ethers.provider.getNetwork();

  // Signed through ethers' own EIP-712 implementation, against the domain the
  // contract reports. If the backend's bytes differ, one of the two has the
  // encoding wrong and every payment would fail as InvalidQuoteSignature.
  const signature = await quoteSigner.signTypedData(
    {
      name: "AeroLedgerEscrow",
      version: "2",
      chainId: Number(network.chainId),
      verifyingContract,
    },
    {
      Quote: [
        { name: "orderHash", type: "bytes32" },
        { name: "buyer", type: "address" },
        { name: "seller", type: "address" },
        { name: "token", type: "address" },
        { name: "amount", type: "uint256" },
        { name: "fee", type: "uint256" },
        { name: "expiry", type: "uint256" },
      ],
    },
    {
      orderHash,
      buyer: INPUT.buyer,
      seller: INPUT.seller,
      token: INPUT.token,
      amount: INPUT.amount,
      fee: INPUT.fee,
      expiry: INPUT.expiry,
    },
  );

  const vector = {
    note:
      "Generated by contracts/ethereum/scripts/emit-eip712-golden.js from the " +
      "contract's own view functions. Checked by the Rust backend's eip712 module " +
      "and by the Hardhat suite, so a drift between them fails a build rather than " +
      "producing signatures the contract rejects as if the key were wrong.",
    input: {
      ...INPUT,
      chainId: Number(network.chainId),
      verifyingContract,
      deployer: deployer.address,
      quoteSigner: quoteSigner.address,
      quoteSignerKey: QUOTE_SIGNER_KEY,
    },
    expected: {
      orderHash,
      domainSeparator,
      quoteDigest,
      signature,
    },
  };

  const out = path.join(__dirname, "..", "test", "eip712_golden.json");
  fs.writeFileSync(out, `${JSON.stringify(vector, null, 2)}\n`, "utf8");
  console.log(`wrote ${out}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
