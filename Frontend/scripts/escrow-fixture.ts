/**
 * Emit the exact bytes the browser would put on-chain, for the Anchor suite to
 * check against the program's own encoding.
 *
 * ## Why a fixture and not a shared import
 *
 * The obvious move is to have the Anchor suite import these modules directly.
 * It does not work: the Anchor package pins ts-node 7, whose loader predates
 * `moduleTypes`, so a `.ts` file under a `"type": "module"` package resolves as
 * ESM and the whole suite falls off its CommonJS loader. Pinning a newer ts-node
 * means regenerating a yarn lockfile that is deliberately committed.
 *
 * A fixture is better anyway. It is a diff you can read, it costs the Anchor
 * suite no dependencies, and it makes the comparison explicit: these bytes, from
 * this input, must equal what Anchor's own client produces. The browser test
 * asserts the committed file still matches what the code emits, so drift fails
 * in CI rather than rotting quietly.
 *
 * This module only builds the fixture, and deliberately imports nothing from
 * Node: it is reached from the browser's own test suite, whose project has no
 * ambient Node types and should not gain them just to read a path.
 * `emit-escrow-fixture.ts` owns the writing, and
 * `escrow/program.test.ts` asserts the committed copy still matches.
 *
 * Regenerate with:
 *     cd Frontend && npx vite-node scripts/emit-escrow-fixture.ts
 */
import { Keypair, PublicKey } from "@solana/web3.js";

import {
  createOrderAccountMetas,
  deriveConfig,
  deriveEscrowVault,
  deriveMerchant,
  deriveOrder,
  deriveSupportedMint,
  deriveWalletAta,
  encodeCreateOrderData,
  orderIdHash,
  quoteMessage,
  WRAPPED_SOL_MINT,
} from "../src/app/lib/escrow/program";

/**
 * Fixed inputs. Deterministic so the fixture is stable in a diff, and derived
 * from seeds rather than hardcoded base58 so a reader can see where they came
 * from. Keys that have an associated token account derived from them must be
 * real curve points, which `fromSeed` guarantees and an arbitrary byte array
 * does not.
 */
const PROGRAM_ID = new PublicKey("Fg6PaFpoGXkYsidMpWxTWqK6W2BeZ7FEfcYkgqPLF6j");
const ORDER_ID = "3f8a1c2e-0b4d-4e6f-9a1b-2c3d4e5f6071";

const wallet = (seed: number) =>
  Keypair.fromSeed(new Uint8Array(32).fill(seed)).publicKey;

const BUYER = wallet(11);
const SELLER = wallet(12);
const PAYOUT_WALLET = wallet(13);
const TREASURY = wallet(14);

const QUOTE = {
  amount: 1_150_000_000n,
  feeAmount: 150_000_000n,
  // Any value: these bytes are compared, never submitted. The program's own
  // lifetime ceiling is checked against the slot clock at execution, which this
  // fixture never reaches.
  expiry: 1_900_000_000n,
};

function hex(bytes: Uint8Array): string {
  return [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
}

export function buildFixture() {
  const order = deriveOrder(PROGRAM_ID, ORDER_ID);
  const metas = createOrderAccountMetas({
    programId: PROGRAM_ID,
    orderId: ORDER_ID,
    buyer: BUYER,
    seller: SELLER,
    payoutWallet: PAYOUT_WALLET,
    treasury: TREASURY,
    mint: WRAPPED_SOL_MINT,
    buyerTokenAccount: deriveWalletAta(BUYER, WRAPPED_SOL_MINT),
  });

  return {
    note: [
      "Generated by Frontend/scripts/emit-escrow-fixture.ts -- do not edit by hand.",
      "These are the exact bytes the browser puts on-chain for the inputs below.",
      "contracts/solana/tests checks them against the program's own encoding, so a",
      "drift between the browser and the program fails a build instead of producing",
      "transactions the validator rejects for reasons that point at the wrong thing.",
    ].join(" "),
    input: {
      programId: PROGRAM_ID.toBase58(),
      orderId: ORDER_ID,
      buyer: BUYER.toBase58(),
      seller: SELLER.toBase58(),
      payoutWallet: PAYOUT_WALLET.toBase58(),
      treasury: TREASURY.toBase58(),
      mint: WRAPPED_SOL_MINT.toBase58(),
      amount: QUOTE.amount.toString(),
      feeAmount: QUOTE.feeAmount.toString(),
      expiry: QUOTE.expiry.toString(),
    },
    derived: {
      orderIdHash: hex(orderIdHash(ORDER_ID)),
      config: deriveConfig(PROGRAM_ID).toBase58(),
      supportedMint: deriveSupportedMint(PROGRAM_ID, WRAPPED_SOL_MINT).toBase58(),
      merchant: deriveMerchant(PROGRAM_ID, SELLER).toBase58(),
      order: order.toBase58(),
      escrowVault: deriveEscrowVault(order, WRAPPED_SOL_MINT).toBase58(),
    },
    /** Anchor instruction data: 8-byte discriminator then Borsh arguments. */
    createOrderData: hex(encodeCreateOrderData(ORDER_ID, QUOTE)),
    /** The canonical message the backend signs, and the program rebuilds. */
    quoteMessage: hex(
      quoteMessage({
        orderId: ORDER_ID,
        buyer: BUYER,
        seller: SELLER,
        mint: WRAPPED_SOL_MINT,
        quote: QUOTE,
      }),
    ),
    /** Positional account list. Anchor matches by position, so order is part of it. */
    accounts: metas.map((m) => ({
      pubkey: m.pubkey.toBase58(),
      isSigner: m.isSigner,
      isWritable: m.isWritable,
    })),
  };
}
