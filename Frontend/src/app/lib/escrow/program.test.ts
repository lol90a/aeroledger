const PROGRAM_ID = new PublicKey("Fg6PaFpoGXkYsidMpWxTWqK6W2BeZ7FEfcYkgqPLF6j");

function hex(bytes: Uint8Array): string {
  return [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * A pubkey of 32 identical bytes. Matches the fixtures the Rust golden-vector
 * test uses, so the two sides sign the same message — but an arbitrary 32-byte
 * array is almost never a valid ed25519 point, so these are only safe where no
 * associated token address is derived from them.
 */
function filled(byte: number): PublicKey {
  return new PublicKey(new Uint8Array(32).fill(byte));
}

/**
 * A deterministic *on-curve* key.
 *
 * Associated token addresses may only be derived for real wallet keys;
 * `getAssociatedTokenAddressSync` rejects anything off the curve, which is the
 * check that stops a PDA being mistaken for a wallet. Deriving from a fixed seed
 * keeps these tests reproducible without hardcoding opaque base58 strings.
 */
function wallet(seed: number): PublicKey {
  return Keypair.fromSeed(new Uint8Array(32).fill(seed)).publicKey;
}

/**
 * The browser and the program must agree on the exact bytes the backend signed.
 * They are written in different languages from the same specification, which is
 * the classic place for a silent divergence: the symptom on-chain is an
 * "unauthorized quote signer" error, which points at the key rather than at the
 * message, and costs an afternoon.
 *
 * The golden vector is generated by the program's own `quote_message` and
 * checked by `contracts/solana/.../quote.rs` and by the backend's
 * `quote_authority` module. This is the third reader of the same file.
 */
describe("quote message (cross-language golden vector)", () => {
  it("reproduces the vector the Rust program generated", () => {
    const golden = GOLDEN_HEX.trim();

    const message = quoteMessage({
      orderId: "booking-1",
      buyer: filled(7),
      seller: filled(8),
      mint: filled(9),
      quote: {
        amount: 1_833_740_832n,
        feeAmount: 15_000_000n,
        expiry: 1_900_000_000n,
      },
    });

    expect(hex(message)).toBe(golden);
  });

  it("is exactly the length the program allocates", () => {
    const message = quoteMessage({
      orderId: "booking-1",
      buyer: filled(7),
      seller: filled(8),
      mint: filled(9),
      quote: { amount: 1n, feeAmount: 0n, expiry: 1n },
    });
    expect(message.length).toBe(QUOTE_MESSAGE_LEN);
    expect(QUOTE_MESSAGE_LEN).toBe(177);
  });

  it("starts with the domain separator, so an old-layout signature cannot be replayed", () => {
    const message = quoteMessage({
      orderId: "x",
      buyer: wallet(1),
      seller: wallet(2),
      mint: filled(3),
      quote: { amount: 10n, feeAmount: 1n, expiry: 99n },
    });
    expect(new TextDecoder().decode(message.subarray(0, 25))).toBe(
      "AEROLEDGER_ORDER_QUOTE_V1",
    );
  });

  it("changes when any single field changes", () => {
    const base = {
      orderId: "booking-1",
      buyer: filled(7),
      seller: filled(8),
      mint: filled(9),
      quote: { amount: 100n, feeAmount: 5n, expiry: 1_900_000_000n },
    };
    const baseline = hex(quoteMessage(base));

    expect(hex(quoteMessage({ ...base, orderId: "booking-2" }))).not.toBe(baseline);
    expect(hex(quoteMessage({ ...base, buyer: filled(6) }))).not.toBe(baseline);
    expect(hex(quoteMessage({ ...base, seller: filled(6) }))).not.toBe(baseline);
    expect(hex(quoteMessage({ ...base, mint: filled(6) }))).not.toBe(baseline);
    expect(
      hex(quoteMessage({ ...base, quote: { ...base.quote, amount: 101n } })),
    ).not.toBe(baseline);
    expect(
      hex(quoteMessage({ ...base, quote: { ...base.quote, feeAmount: 6n } })),
    ).not.toBe(baseline);
    expect(
      hex(quoteMessage({ ...base, quote: { ...base.quote, expiry: 1_900_000_001n } })),
    ).not.toBe(baseline);
  });
});

/**
 * Anchor's discriminators are the first eight bytes of a SHA-256 over a
 * namespaced name. They are computed here rather than pasted in, so these tests
 * pin the *values* that the program will be looking for.
 */
describe("anchor identifiers", () => {
  it("derives the create_order instruction tag", () => {
    expect(hex(anchorDiscriminator("global:create_order"))).toBe("8d3625cfedd2fad7");
  });

  it("derives the account tags the decoders check", () => {
    expect(hex(anchorDiscriminator("account:Order"))).toBe("86addfb94d561c33");
  });

  it("hashes order ids with keccak256, not SHA3-256", () => {
    // The two differ only in padding, so a wrong choice derives a plausible
    // address that simply is not the one the program derives.
    expect(hex(orderIdHash("abc"))).toBe(
      "4e03657aea45a94fc7d47ba826c8d667c0d1e6e33a64a036ec44f58fa12d6c45",
    );
  });
});

describe("program-derived addresses", () => {
  it("derives the order PDA from the keccak hash of the id", () => {
    const expected = PublicKey.findProgramAddressSync(
      [new TextEncoder().encode("order"), orderIdHash("booking-1")],
      PROGRAM_ID,
    )[0];
    expect(deriveOrder(PROGRAM_ID, "booking-1").toBase58()).toBe(expected.toBase58());
  });

  it("seeds the merchant PDA with the seller authority, not the payout wallet", () => {
    const seller = wallet(4);
    const payout = wallet(5);
    expect(deriveMerchant(PROGRAM_ID, seller).toBase58()).not.toBe(
      deriveMerchant(PROGRAM_ID, payout).toBase58(),
    );
  });

  it("derives distinct supported-mint PDAs per mint", () => {
    expect(deriveSupportedMint(PROGRAM_ID, WRAPPED_SOL_MINT).toBase58()).not.toBe(
      deriveSupportedMint(PROGRAM_ID, filled(3)).toBase58(),
    );
  });

  it("derives the escrow vault as an off-curve ATA of the order PDA", () => {
    const order = deriveOrder(PROGRAM_ID, "booking-1");
    // The default `allowOwnerOffCurve: false` throws for a PDA owner, so this
    // asserts the client passes true — otherwise every order would fail to build.
    const expected = getAssociatedTokenAddressSync(WRAPPED_SOL_MINT, order, true);
    const metas = createOrderAccountMetas({
      programId: PROGRAM_ID,
      orderId: "booking-1",
      buyer: wallet(1),
      seller: wallet(2),
      payoutWallet: wallet(3),
      treasury: wallet(4),
      mint: WRAPPED_SOL_MINT,
      buyerTokenAccount: wallet(5),
    });
    expect(metas[7]?.pubkey.toBase58()).toBe(expected.toBase58());
  });
});

/**
 * Anchor matches accounts by position. A transposition does not raise an error
 * at build time; it hands the program a different account in a slot whose
 * constraints may happen to pass, which is far worse than a crash.
 */
describe("create_order account metas", () => {
  const params = {
    programId: PROGRAM_ID,
    orderId: "booking-1",
    buyer: wallet(1),
    seller: wallet(2),
    payoutWallet: wallet(3),
    treasury: wallet(4),
    mint: WRAPPED_SOL_MINT,
    buyerTokenAccount: wallet(5),
  };

  it("lists exactly the sixteen accounts the struct declares, in order", () => {
    const metas = createOrderAccountMetas(params);
    const order = deriveOrder(PROGRAM_ID, params.orderId);

    expect(metas.map((m) => m.pubkey.toBase58())).toEqual([
      deriveConfig(PROGRAM_ID).toBase58(),
      deriveSupportedMint(PROGRAM_ID, params.mint).toBase58(),
      deriveMerchant(PROGRAM_ID, params.seller).toBase58(),
      order.toBase58(),
      params.buyer.toBase58(),
      params.mint.toBase58(),
      params.buyerTokenAccount.toBase58(),
      getAssociatedTokenAddressSync(params.mint, order, true).toBase58(),
      getAssociatedTokenAddressSync(params.mint, params.payoutWallet).toBase58(),
      params.payoutWallet.toBase58(),
      getAssociatedTokenAddressSync(params.mint, params.treasury).toBase58(),
      params.treasury.toBase58(),
      SYSVAR_INSTRUCTIONS_PUBKEY.toBase58(),
      TOKEN_PROGRAM_ID.toBase58(),
      ASSOCIATED_TOKEN_PROGRAM_ID.toBase58(),
      SystemProgram.programId.toBase58(),
    ]);
  });

  it("marks only the buyer as a signer", () => {
    const metas = createOrderAccountMetas(params);
    expect(metas.filter((m) => m.isSigner).map((m) => m.pubkey.toBase58())).toEqual([
      params.buyer.toBase58(),
    ]);
  });

  it("marks exactly the accounts the program mutates as writable", () => {
    const metas = createOrderAccountMetas(params);
    // order (init), buyer (pays rent), buyer token account (debited),
    // escrow vault (init). The payout and treasury accounts are read-only here —
    // they are only validated at creation, and paid at completion.
    expect(metas.map((m) => m.isWritable)).toEqual([
      false, false, false, true, true, false, true, true,
      false, false, false, false, false, false, false, false,
    ]);
  });
});

describe("create_order instruction data", () => {
  const quote = { amount: 1_000_000_000n, feeAmount: 25_000_000n, expiry: 1_900_000_000n };

  it("is the discriminator, a Borsh string, then three little-endian integers", () => {
    const data = encodeCreateOrderData("booking-1", quote);

    expect(data.length).toBe(8 + 4 + "booking-1".length + 8 + 8 + 8);
    expect(hex(data.subarray(0, 8))).toBe("8d3625cfedd2fad7");
    // u32 little-endian length prefix: 9 bytes of "booking-1".
    expect([...data.subarray(8, 12)]).toEqual([9, 0, 0, 0]);
    expect(new TextDecoder().decode(data.subarray(12, 21))).toBe("booking-1");

    const view = new DataView(data.buffer, data.byteOffset);
    expect(view.getBigUint64(21, true)).toBe(quote.amount);
    expect(view.getBigUint64(29, true)).toBe(quote.feeAmount);
    expect(view.getBigInt64(37, true)).toBe(quote.expiry);
  });

  it("counts the Borsh length prefix in bytes, not characters", () => {
    // The program checks `order_id.as_bytes().len()`, so a multi-byte character
    // must be counted the same way or the two disagree about the limit.
    const data = encodeCreateOrderData("é", quote);
    expect([...data.subarray(8, 12)]).toEqual([2, 0, 0, 0]);
  });

  it("refuses an order id longer than the program accepts", () => {
    expect(() => encodeCreateOrderData("a".repeat(MAX_ORDER_ID_LEN + 1), quote)).toThrow(
      /max 64/,
    );
    expect(() => encodeCreateOrderData("a".repeat(MAX_ORDER_ID_LEN), quote)).not.toThrow();
  });

  it("refuses an empty order id", () => {
    expect(() => encodeCreateOrderData("", quote)).toThrow(/must not be empty/);
  });

  it("refuses a fee that is not strictly less than the amount", () => {
    // The program carves the fee out of the escrowed amount, so a fee equal to
    // it would leave the seller with nothing.
    expect(() =>
      encodeCreateOrderData("booking-1", { ...quote, feeAmount: quote.amount }),
    ).toThrow(/strictly less/);
  });

  it("refuses a zero amount", () => {
    expect(() =>
      encodeCreateOrderData("booking-1", { amount: 0n, feeAmount: 0n, expiry: 1n }),
    ).toThrow(/must be positive/);
  });

  it("encodes amounts above 2^53 exactly", () => {
    // A `number` would have lost precision here. Base units reach this range:
    // 2^53 lamports is about 9 million SOL.
    const huge = 9_007_199_254_740_993n; // 2^53 + 1
    const data = encodeCreateOrderData("booking-1", {
      amount: huge,
      feeAmount: 1n,
      expiry: 1n,
    });
    const view = new DataView(data.buffer, data.byteOffset);
    expect(view.getBigUint64(21, true)).toBe(huge);
  });
});

/**
 * The program re-reads this instruction out of the Instructions sysvar and
 * parses the sixteen-byte header itself. These assertions mirror
 * `verify_quote_signature_data` in `quote.rs`: if web3.js ever changed the
 * layout it emits, every payment would fail on-chain with `MalformedQuoteSignature`.
 */
describe("Ed25519 quote attestation", () => {
  const signature = new Uint8Array(64).fill(0xab);
  const message = quoteMessage({
    orderId: "booking-1",
    buyer: filled(7),
    seller: filled(8),
    mint: filled(9),
    quote: { amount: 100n, feeAmount: 1n, expiry: 1_900_000_000n },
  });
  const quoteAuthority = filled(11);

  const ix = buildQuoteAttestationInstruction({ quoteAuthority, message, signature });
  const data = new Uint8Array(ix.data);
  const u16 = (at: number) => new DataView(data.buffer, data.byteOffset).getUint16(at, true);

  it("targets the native Ed25519 program with no accounts", () => {
    expect(ix.programId.toBase58()).toBe("Ed25519SigVerify111111111111111111111111111");
    expect(ix.keys).toHaveLength(0);
  });

  it("verifies exactly one signature", () => {
    // The program rejects anything else: several signatures would let an
    // attacker bury the expected one among others and reuse the offsets.
    expect(data[0]).toBe(1);
  });

  it("keeps the signature, key and message inside this instruction", () => {
    // 0xffff is the "this same instruction" sentinel. Any other index points at
    // bytes the program has not inspected, so it refuses them.
    expect(u16(4)).toBe(0xffff);
    expect(u16(8)).toBe(0xffff);
    expect(u16(14)).toBe(0xffff);
  });

  it("points at the key and message the program will compare", () => {
    expect(hex(data.subarray(u16(6), u16(6) + 32))).toBe(hex(quoteAuthority.toBytes()));
    expect(u16(12)).toBe(QUOTE_MESSAGE_LEN);
    expect(hex(data.subarray(u16(10), u16(10) + QUOTE_MESSAGE_LEN))).toBe(hex(message));
  });

  it("is 289 bytes: header, key, signature, message", () => {
    expect(data.length).toBe(16 + 32 + 64 + QUOTE_MESSAGE_LEN);
  });

  it("refuses a signature that is not 64 bytes", () => {
    expect(() =>
      buildQuoteAttestationInstruction({
        quoteAuthority,
        message,
        signature: new Uint8Array(63),
      }),
    ).toThrow(/64 bytes/);
  });
});

describe("buildCreateOrderInstruction", () => {
  it("combines the metas and the encoded data", () => {
    const ix = buildCreateOrderInstruction(
      {
        programId: PROGRAM_ID,
        orderId: "booking-1",
        buyer: wallet(1),
        seller: wallet(2),
        payoutWallet: wallet(3),
        treasury: wallet(4),
        mint: WRAPPED_SOL_MINT,
        buyerTokenAccount: wallet(5),
      },
      { amount: 100n, feeAmount: 1n, expiry: 1n },
    );
    expect(ix.programId.toBase58()).toBe(PROGRAM_ID.toBase58());
    expect(ix.keys).toHaveLength(16);
    expect(hex(new Uint8Array(ix.data.subarray(0, 8)))).toBe("8d3625cfedd2fad7");
  });
});

/**
 * The Anchor suite cannot import these modules: its package pins ts-node 7,
 * whose loader predates `moduleTypes`, so a `.ts` file under a `"type":
 * "module"` package resolves as ESM and the whole suite falls off its CommonJS
 * loader. It reads a committed fixture of these bytes instead, and checks them
 * against the program's own encoding.
 *
 * A fixture only works if it is current. This is what keeps it honest: if the
 * encoding changes and nobody regenerates, the browser's own suite fails here
 * and says what to run.
 */
describe("the fixture the Anchor suite checks against", () => {
  it("still matches what this code emits", () => {
    expect(buildFixture()).toEqual(COMMITTED_FIXTURE);
  });
});
